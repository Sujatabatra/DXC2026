package com.sujata.demo;

public class DatatTypesClass {

	public static void main(String[] args) {
		
		/*
		 * Keywords : reserved words of the language
		 * identifiers : any words used to identofy different things of code, like variable names, method names, class names, package names
		 * literals : any values
		 *
		 * whenever you are giving integer category literal by default that literal will be of the type int
		 * whenever you are giving floating point category literal by default that literal will be of the type double
		 */
		
		int value=10;
		/*
		 * destination type : 8 bytes and our literal is by default of int which is 4 bytes 
		 * by prefixing integer literal with l/L , we are specifying that literal is of the type long not default int
		 */
		long num=45L;
		
		/*
		 * destination type : 4 bytes and my literal is by default of long which is 8 bytes
		 * by prefixing floating point literal with f/F , we are specifying that literal is of the type float not default double
		 */
		float number=5.6f;
		
		
		
		

	}

}
