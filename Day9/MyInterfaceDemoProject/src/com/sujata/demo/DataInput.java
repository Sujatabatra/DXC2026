package com.sujata.demo;

public class DataInput {

	private int value;
	
	public DataInput() {
		
	}

	public DataInput(int value) {
		super();
		this.value = value;
	}

	public int getValue() {
		return value;
	}

	public void setValue(int value) {
		this.value = value;
	}
	
	
}
